// One policy for Worker responses and generated Cloudflare static-asset headers.
export function contentSecurityPolicy({nonce='',development=false}={}) {
  const scripts=["'self'",...(nonce?[`'nonce-${nonce}'`]:[]),'https://www.googletagmanager.com','https://www.google-analytics.com'];
  if(development)scripts.push("'unsafe-eval'");
  return [
    "default-src 'self'",`script-src ${scripts.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https://*.google-analytics.com https://www.googletagmanager.com",
    "font-src 'self' data:",
    "connect-src 'self' https://formsubmit.co https://*.google-analytics.com https://www.googletagmanager.com"+(development?' ws: wss:':''),
    "frame-src https://www.google.com https://maps.google.com",
    "worker-src 'self' blob:","object-src 'none'","base-uri 'self'","form-action 'self'",
    // Keep the owner's existing ChatGPT preview usable while preventing arbitrary framing.
    "frame-ancestors 'self' https://chatgpt.com https://*.chatgpt.com",
    ...(!development?['upgrade-insecure-requests']:[])
  ].join('; ');
}
export function securityHeaders(options={}) {
  return {
    'X-Content-Type-Options':'nosniff',
    'X-Frame-Options':'SAMEORIGIN',
    'Strict-Transport-Security':'max-age=31536000',
    'Referrer-Policy':'strict-origin-when-cross-origin',
    'Permissions-Policy':'camera=(), microphone=(), geolocation=()',
    'Content-Security-Policy':contentSecurityPolicy(options)
  };
}
export function renderRequest(request,{nonce,development=false}) {
  const headers=new Headers(request.headers);
  // Vinext reads the request policy to nonce its hydration scripts.
  headers.set('Content-Security-Policy',contentSecurityPolicy({nonce,development}));
  // The pinned renderer otherwise streams metadata for empty User-Agent values,
  // even when htmlLimitedBots=/.*/. This is an internal renderer identity only.
  if(!headers.get('User-Agent'))headers.set('User-Agent','VBKMetadataRenderer/1.0');
  return new Request(request,{headers});
}
export function secureResponse(response,{nonce='',development=false,canonical=''}={}) {
  const headers=new Headers(response.headers);
  for(const [name,value] of Object.entries(securityHeaders({nonce,development})))headers.set(name,value);
  if(canonical&&response.ok&&headers.get('content-type')?.includes('text/html'))headers.set('Link',`<${canonical}>; rel="canonical"`);
  return new Response(response.body,{status:response.status,statusText:response.statusText,headers});
}
export function staticSecurityHeaders() {
  return '# Generated by scripts/prepare-public.mjs from lib/security-headers.mjs\n/*\n'+Object.entries(securityHeaders()).map(([name,value])=>`  ${name}: ${value}`).join('\n')+'\n';
}
